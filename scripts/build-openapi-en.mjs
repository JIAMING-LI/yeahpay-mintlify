function translate(value) {
  if (typeof value === "string") {
    return translations.get(value) ?? value;
  }
  if (Array.isArray(value)) {
    return value.map(translate);
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, nestedValue]) => [key, translate(nestedValue)])
    );
  }
  return value;
}

const output = translate(source);
const serialized = `${JSON.stringify(output, null, 2)}\n`;
const untranslated = [...new Set(serialized.match(/[^"\n]*[\u3400-\u9fff][^"\n]*/g) ?? [])];

if (untranslated.length > 0) {
  throw new Error(`Untranslated Chinese strings:\n${untranslated.join("\n")}`);
}

await writeFile(new URL("../openapi-en.json", import.meta.url), serialized);
